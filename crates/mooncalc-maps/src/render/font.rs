//! A tiny built-in 5x7 bitmap font for printable ASCII (plus `°`), drawn
//! for this project. Each glyph is seven rows of five bits, most
//! significant bit leftmost; the advance is six columns.

pub(crate) const GLYPH_W: u32 = 5;
pub(crate) const GLYPH_H: u32 = 7;
pub(crate) const ADVANCE: u32 = 6;

/// Parses `"01110 10001 ..."` into seven row bitmasks at compile time.
const fn g(s: &[u8]) -> [u8; 7] {
    let mut rows = [0u8; 7];
    let mut r = 0;
    let mut i = 0;
    while i < s.len() {
        let c = s[i];
        if c == b' ' {
            r += 1;
        } else {
            rows[r] = (rows[r] << 1) | (c - b'0');
        }
        i += 1;
    }
    rows
}

