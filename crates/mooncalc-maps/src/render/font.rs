const DEGREE: [u8; 7] = g(b"01100 10010 10010 01100 00000 00000 00000");

/// The glyph for `c`; unsupported characters render as `?`.
pub(crate) fn glyph(c: char) -> [u8; 7] {
    match c {
        ' '..='~' => ASCII[c as usize - 32],
        '°' => DEGREE,
        _ => ASCII[(b'?' - 32) as usize],
    }
}

/// Width in pixels of `text` at integer `scale`.
pub(crate) fn text_width(text: &str, scale: u32) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 {
        0
    } else {
        (n * ADVANCE - (ADVANCE - GLYPH_W)) * scale
    }
}

/// Calls `plot(x, y)` for every set pixel of `text` drawn with its top-left
/// corner at (`x0`, `y0`) and integer `scale`.
pub(crate) fn for_each_pixel(
    text: &str,
    x0: i32,
    y0: i32,
    scale: u32,
    mut plot: impl FnMut(i32, i32),
) {
    let s = scale.max(1) as i32;
    for (i, c) in text.chars().enumerate() {
        let gx = x0 + i as i32 * ADVANCE as i32 * s;
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..GLYPH_W as i32 {
                if bits >> (GLYPH_W as i32 - 1 - col) & 1 == 1 {
                    for dy in 0..s {
                        for dx in 0..s {
                            plot(gx + col * s + dx, y0 + row as i32 * s + dy);
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_fit_five_columns() {
        for g in ASCII.iter().chain([&DEGREE]) {
            assert!(g.iter().all(|&r| r < 32));
        }
        assert_eq!(
            glyph('A'),
            [
                0b01110, 0b10001, 0b10001, 0b10001, 0b11111, 0b10001, 0b10001
            ]
        );
        assert_eq!(glyph('é'), glyph('?'));
        assert_eq!(text_width("AB", 2), 22);
    }
}
