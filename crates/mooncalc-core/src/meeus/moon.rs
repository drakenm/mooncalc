#[cfg(test)]
mod tests {
    use super::*;
    use crate::angle::ARCSEC;
    use crate::transform::ecliptic_to_equatorial;

    #[test]
    fn meeus_47a() {
        // 1992 April 12, 0h TD (JDE 2448724.5):
        // L′ = 134.290182°, D = 113.842304°, M = 97.643514°,
        // M′ = 5.150833°, F = 219.889721°, E = 1.000194;
        // λ = 133.162655°, β = −3.229126°, Δ = 368409.7 km;
        // apparent λ = 133.167265°, α = 134.688470°, δ = +13.768368°.
        let jd = 2_448_724.5;
        let [lp, d, m, mp, f] = fundamental_arguments(jd);
        for (got, want) in [
            (lp, 134.290_182),
            (d, 113.842_304),
            (m, 97.643_514),
            (mp, 5.150_833),
            (f, 219.889_721),
        ] {
            assert!(
                (norm_2pi(got) / DEG - want).abs() < 1e-6,
                "{} vs {want}",
                got / DEG
            );
        }
        let mean = moon_mean_ecliptic(jd);
        assert!((mean.lon / DEG - 133.162_655).abs() < 1e-6);
        assert!((mean.lat / DEG + 3.229_126).abs() < 1e-6);
        assert!((mean.distance_km - 368_409.7).abs() < 0.1);

        let nut = NutationObliquity::at(jd);
        let app = moon_apparent_ecliptic(jd, &nut);
        assert!((app.lon / DEG - 133.167_265).abs() < 2e-6);
        assert!((nut.eps / DEG - 23.440_636).abs() < 2e-6);
        let eq = ecliptic_to_equatorial(&app, nut.eps);
        assert!(
            (eq.ra / DEG - 134.688_470).abs() < 2e-6,
            "{}",
            (eq.ra / DEG - 134.688_470) * 3600.0
        );
        assert!((eq.dec / DEG - 13.768_368).abs() < 2e-6);
        let _ = ARCSEC;
    }
}
