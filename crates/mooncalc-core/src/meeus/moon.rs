//! The Moon from ELP-2000/82 as truncated by Meeus, *Astronomical
//! Algorithms* 2nd ed., ch. 47 (Tables 47.A and 47.B, the additive A1/A2/A3
//! terms and the eccentricity factor E). Accuracy about 10″ in longitude
//! and 4″ in latitude near the present (Meeus ch. 47).

use crate::angle::{DEG, norm_2pi};
use crate::coords::Ecliptic;
use crate::nutation::NutationObliquity;
use crate::time::centuries_since_j2000;

/// Degrees polynomial reduced modulo 360 then converted to radians.
#[inline]
fn deg_poly(t: f64, c: [f64; 5]) -> f64 {
    let v = c[0] + t * (c[1] + t * (c[2] + t * (c[3] + t * c[4])));
    (v % 360.0) * DEG
}

/// Fundamental arguments of the Moon (Meeus eqs. 47.1–47.5), radians:
/// `[L′, D, M, M′, F]`.
pub fn fundamental_arguments(jd_tt: f64) -> [f64; 5] {
    let t = centuries_since_j2000(jd_tt);
    [
        deg_poly(
            t,
            [
                218.316_447_7,
                481_267.881_234_21,
                -0.001_578_6,
                1.0 / 538_841.0,
                -1.0 / 65_194_000.0,
            ],
        ),
        deg_poly(
            t,
            [
                297.850_192_1,
                445_267.111_403_4,
                -0.001_881_9,
                1.0 / 545_868.0,
                -1.0 / 113_065_000.0,
            ],
        ),
        deg_poly(
            t,
            [
                357.529_109_2,
                35_999.050_290_9,
                -0.000_153_6,
                1.0 / 24_490_000.0,
                0.0,
            ],
        ),
        deg_poly(
            t,
            [
                134.963_396_4,
                477_198.867_505_5,
                0.008_741_4,
                1.0 / 69_699.0,
                -1.0 / 14_712_000.0,
            ],
        ),
        deg_poly(
            t,
            [
                93.272_095_0,
                483_202.017_523_3,
                -0.003_653_9,
                -1.0 / 3_526_000.0,
                1.0 / 863_310_000.0,
            ],
        ),
    ]
}

/// Geocentric ecliptic position of the Moon referred to the **mean**
/// equinox of date (no nutation), distance in km (Meeus ch. 47).
pub fn moon_mean_ecliptic(jd_tt: f64) -> Ecliptic {
    let t = centuries_since_j2000(jd_tt);
    let [lp, d, m, mp, f] = fundamental_arguments(jd_tt);
    let a1 = ((119.75 + 131.849 * t) % 360.0) * DEG;
    let a2 = ((53.09 + 479_264.290 * t) % 360.0) * DEG;
    let a3 = ((313.45 + 481_266.484 * t) % 360.0) * DEG;
    let e = 1.0 - t * (0.002_516 + 0.000_007_4 * t);
    let e_factor = [1.0, e, e * e];

    let mut sl = 0.0;
    let mut sr = 0.0;
    for row in &TABLE_47A {
        let arg = row[0] * d + row[1] * m + row[2] * mp + row[3] * f;
        let (s, c) = arg.sin_cos();
        let k = e_factor[row[1].abs() as usize];
        sl += row[4] * k * s;
        sr += row[5] * k * c;
    }
    let mut sb = 0.0;
    for row in &TABLE_47B {
        let arg = row[0] * d + row[1] * m + row[2] * mp + row[3] * f;
        sb += row[4] * e_factor[row[1].abs() as usize] * arg.sin();
    }
    // Additive terms (Venus, Jupiter, flattening of the Earth).
    sl += 3958.0 * a1.sin() + 1962.0 * (lp - f).sin() + 318.0 * a2.sin();
    sb += -2235.0 * lp.sin()
        + 382.0 * a3.sin()
        + 175.0 * (a1 - f).sin()
        + 175.0 * (a1 + f).sin()
        + 127.0 * (lp - mp).sin()
        - 115.0 * (lp + mp).sin();

    Ecliptic {
        lon: norm_2pi(lp + sl * 1e-6 * DEG),
        lat: sb * 1e-6 * DEG,
        distance_km: 385_000.56 + sr * 1e-3,
    }
}

/// Apparent geocentric ecliptic position of the Moon (true equinox of
/// date): the mean position plus nutation in longitude (Meeus ch. 47).
/// Light time (~0.7″) is neglected, as in Meeus.
pub fn moon_apparent_ecliptic(jd_tt: f64, nut: &NutationObliquity) -> Ecliptic {
    let mut e = moon_mean_ecliptic(jd_tt);
    e.lon = norm_2pi(e.lon + nut.dpsi);
    e
}

