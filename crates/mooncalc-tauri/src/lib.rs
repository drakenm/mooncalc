//! MoonCalc Tauri shell.
//!
//! The webview UI lives in `frontend/tauri/` (Vite + TypeScript). It reaches
//! Rust only through the commands in [`commands`], whose inputs and outputs are
//! the serde types in [`dto`]. The logic behind them is in [`services`], which
//! has no Tauri dependency and is destined for the shared `mooncalc-app` crate.
//!
//! | Command | Input | Output |
//! | --- | --- | --- |
//! | `app_info` | none | [`dto::AppInfo`] |
//! | `criteria_list` | none | `Vec<`[`dto::CriterionInfo`]`>` |
//! | `compute_visibility_map` | [`dto::MapParams`] | [`dto::MapResult`] |
//! | `location_report` | [`dto::LocationReportParams`] | [`dto::LocationReport`] |
//! | `search_cities` | [`dto::CitySearchParams`] | `Vec<`[`dto::City`]`>` |
//!
//! Errors are [`dto::ApiError`] values. Each command has a matching
//! `allow-<command>` permission (generated by `build.rs`), granted to the main
//! window in `capabilities/default.json` and nothing else.

pub mod codec;
pub mod commands;
pub mod dto;
pub mod services;
mod synthetic;

/// Start the desktop application.
pub fn run() {
    tauri::Builder::default()
        .invoke_handler(tauri::generate_handler![
            commands::app_info,
            commands::criteria_list,
            commands::compute_visibility_map,
            commands::location_report,
            commands::search_cities,
        ])
        .run(tauri::generate_context!())
        .expect("error while running MoonCalc");
}

#[cfg(test)]
mod tests {
    //! Wire-format tests: what the TypeScript side sends and receives.

    use crate::dto::*;
    use serde_json::json;

    #[test]
    fn map_params_accept_the_typescript_shape() {
        let p: MapParams = serde_json::from_value(json!({
            "date": { "year": 2026, "month": 11, "day": 10 },
            "criterionId": "yallop",
            "crescent": "morning",
            "resolutionDeg": 0.5
        }))
        .unwrap();
        assert_eq!(p.crescent, Crescent::Morning);
        assert_eq!(p.ephemeris_id, None);
    }

    #[test]
    fn results_serialize_in_camel_case() {
        let v = serde_json::to_value(Location {
            lat_deg: 1.0,
            lon_deg: 2.0,
            elevation_m: 3.0,
        })
        .unwrap();
        assert_eq!(
            v,
            json!({ "latDeg": 1.0, "lonDeg": 2.0, "elevationM": 3.0 })
        );

        let e = serde_json::to_value(ApiError::invalid_params("x")).unwrap();
        assert_eq!(e, json!({ "code": "invalid-params", "message": "x" }));

        let r = crate::services::compute_visibility_map(&MapParams {
            date: CivilDate {
                year: 2026,
                month: 11,
                day: 10,
            },
            criterion_id: "odeh".into(),
            crescent: Crescent::Evening,
            resolution_deg: 10.0,
            ephemeris_id: None,
        })
        .unwrap();
        let v = serde_json::to_value(&r).unwrap();
        for key in [
            "criterionId",
            "date",
            "crescent",
            "grid",
            "cells",
            "noData",
            "legend",
            "computeMs",
            "synthetic",
        ] {
            assert!(v.get(key).is_some(), "missing {key}");
        }
        assert_eq!(v["crescent"], "evening");
        assert_eq!(v["grid"]["latMinDeg"], -90.0);
    }
}
