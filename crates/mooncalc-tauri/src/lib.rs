//! MoonCalc Tauri shell.
//!
//! The webview UI lives in `frontend/tauri/` (Vite + TypeScript). It reaches
//! Rust only through the commands in [`commands`], whose inputs and outputs are
//! the serde DTOs of [`mooncalc_app::dto`]. The logic behind them is the
//! shared `mooncalc-app` services crate; this crate adds only native
//! concerns: threads ([`parallel`]), clocks for timing, the per-window
//! [`AppState`] and DE440 loading from a path.
//!
//! | Command | Input | Output |
//! | --- | --- | --- |
//! | `app_info` | none | `AppInfo` |
//! | `criteria_list` | none | `Vec<CriterionInfo>` |
//! | `compute_visibility_map` | `MapParams` | `MapResult` |
//! | `export_map_png` | `ExportPngParams` | `PngImage` |
//! | `save_map_png` | `ExportPngParams` | [`commands::SavedFile`] (written to Downloads) |
//! | `location_report` | `LocationReportParams` | `LocationReport` |
//! | `search_cities` | `CitySearchParams` | `Vec<City>` |
//! | `nearest_city` | `NearestCityParams` | `Option<NearestCity>` |
//! | `earliest_sighting` | `EarliestParams` | `EarliestResult` |
//! | `basemap` | `BasemapParams` | `Basemap` |
//! | `load_de440` | `LoadDe440Params` | `EphemerisBackendInfo` |
//!
//! Errors are `ApiError` values. Each command has a matching `allow-<command>`
//! permission (generated by `build.rs`), granted to the main window in
//! `capabilities/default.json` and nothing else.

pub mod commands;
pub mod parallel;

use std::sync::atomic::AtomicU64;
use std::sync::{Arc, Mutex, RwLock};

use mooncalc_app::dto::{ApiError, EphemerisBackendInfo};
use mooncalc_app::ephemeris::{Ephemerides, Ephemeris};
use mooncalc_app::map::MapOutput;

/// Shared state of the running app.
#[derive(Debug, Default)]
pub struct AppState {
    ephemerides: RwLock<Ephemerides>,
    /// Incremented by every map request; a running map stops when it
    /// changes (superseded by a newer request).
    pub map_generation: AtomicU64,
    /// The last computed map, reused by `export_map_png`.
    pub last_map: Mutex<Option<Arc<MapOutput>>>,
}

impl AppState {
    /// A snapshot of the session's ephemerides.
    pub fn ephemerides(&self) -> Ephemerides {
        self.ephemerides
            .read()
            .unwrap_or_else(|e| e.into_inner())
            .clone()
    }

    /// The ephemeris for an id (`None` = the default).
    pub fn ephemeris(&self, id: Option<&str>) -> Result<Arc<dyn Ephemeris>, ApiError> {
        self.ephemerides
            .read()
            .unwrap_or_else(|e| e.into_inner())
            .get(id)
    }

    /// Load a DE440 file and use it for the `de440` backend.
    pub fn load_de440(&self, path: &str) -> Result<EphemerisBackendInfo, ApiError> {
        #[cfg(feature = "de440")]
        {
            // Open outside the lock; only the swap holds it.
            let eph = mooncalc_app::ephemeris::de440_open(path)?;
            let mut e = self.ephemerides.write().unwrap_or_else(|e| e.into_inner());
            e.set_de440(path.trim(), eph);
            *self.last_map.lock().unwrap_or_else(|e| e.into_inner()) = None;
            Ok(e.backend(mooncalc_app::ephemeris::DE440)
                .expect("de440 is listed"))
        }
        #[cfg(not(feature = "de440"))]
        {
            let _ = path;
            Err(ApiError::ephemeris_unavailable(
                "this build has no DE440 support (rebuild with `--features de440`)",
            ))
        }
    }
}

/// Start the desktop application.
pub fn run() {
    tauri::Builder::default()
        .manage(Arc::new(AppState::default()))
        .invoke_handler(tauri::generate_handler![
            commands::app_info,
            commands::criteria_list,
            commands::compute_visibility_map,
            commands::export_map_png,
            commands::save_map_png,
            commands::location_report,
            commands::search_cities,
            commands::nearest_city,
            commands::earliest_sighting,
            commands::basemap,
            commands::load_de440,
        ])
        .run(tauri::generate_context!())
        .expect("error while running MoonCalc");
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn state_serves_the_default_ephemeris() {
        let s = AppState::default();
        assert!(s.ephemeris(None).is_ok());
        assert!(s.ephemeris(Some("nope")).is_err());
        let r = s.load_de440("does-not-exist.bsp");
        assert!(r.is_err());
    }
}
