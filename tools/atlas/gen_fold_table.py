#!/usr/bin/env python3
"""Generate crates/mooncalc-atlas/src/fold_table.rs.

The table maps the Latin-1 Supplement, Latin Extended-A/B (U+00C0..U+024F)
and Latin Extended Additional (U+1E00..U+1EFF) letters to lower-case ASCII,
using Unicode NFKD decomposition (from Python's unicodedata) plus a few
letters that have no decomposition (ß, æ, ø, ł, đ ...). Characters that do
not fold to ASCII map to their own lower-case form.

Usage: python -I tools/atlas/gen_fold_table.py
"""

import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)),
                   "crates", "mooncalc-atlas", "src", "fold_table.rs")

SPECIAL = {
    "ß": "ss", "ẞ": "ss", "æ": "ae", "Æ": "ae", "ø": "o", "Ø": "o",
    "œ": "oe", "Œ": "oe", "þ": "th", "Þ": "th", "ð": "d", "Ð": "d",
    "đ": "d", "Đ": "d", "ħ": "h", "Ħ": "h", "ı": "i", "ł": "l", "Ł": "l",
    "ŀ": "l", "Ŀ": "l", "ŧ": "t", "Ŧ": "t", "ĸ": "k", "ŋ": "n", "Ŋ": "n",
    "ƀ": "b", "Ɓ": "b", "ƈ": "c", "Ƈ": "c", "Ɗ": "d", "ƌ": "d", "ƒ": "f",
    "Ƒ": "f", "ɠ": "g", "Ɠ": "g", "ƙ": "k", "Ƙ": "k", "ƚ": "l", "Ɲ": "n",
    "ƞ": "n", "Ɵ": "o", "ƥ": "p", "Ƥ": "p", "ƫ": "t", "ƭ": "t", "Ƭ": "t",
    "Ʈ": "t", "Ʋ": "v", "ƴ": "y", "Ƴ": "y", "ƶ": "z", "Ƶ": "z", "ȡ": "d",
    "ȴ": "l", "ȵ": "n", "ȶ": "t", "ȷ": "j", "ȸ": "db", "ȹ": "qp", "Ⱥ": "a",
    "Ȼ": "c", "ȼ": "c", "Ƚ": "l", "Ⱦ": "t", "ȿ": "s", "ɀ": "z", "Ƀ": "b",
    "Ʉ": "u", "Ɇ": "e", "ɇ": "e", "Ɉ": "j", "ɉ": "j", "Ɋ": "q", "ɋ": "q",
    "Ɍ": "r", "ɍ": "r", "Ɏ": "y", "ɏ": "y", "Ǆ": "dz", "ǅ": "dz", "ǆ": "dz",
    "Ǉ": "lj", "ǈ": "lj", "ǉ": "lj", "Ǌ": "nj", "ǋ": "nj", "ǌ": "nj",
    "Ǳ": "dz", "ǲ": "dz", "ǳ": "dz", "×": "x", "÷": " ",
}


def fold(c):
    if c in SPECIAL:
        return SPECIAL[c]
    d = unicodedata.normalize("NFKD", c)
    d = "".join(x for x in d if not unicodedata.combining(x)).lower()
    if d and all(ord(x) < 128 for x in d):
        return d
    return c.lower()


def table(name, lo, hi):
    items = []
    for cp in range(lo, hi + 1):
        s = fold(chr(cp))
        items.append('"%s"' % s.replace("\\", "\\\\").replace('"', '\\"'))
    lines = []
    for i in range(0, len(items), 16):
        lines.append("    " + ", ".join(items[i:i + 16]) + ",")
    return ("/// Folds U+%04X..=U+%04X.\npub(crate) static %s: [&str; %d] = [\n%s\n];\n"
            % (lo, hi, name, hi - lo + 1, "\n".join(lines)))


def main():
    out = ["// @generated by tools/atlas/gen_fold_table.py from Unicode NFKD data"
           " (Python unicodedata %s). Do not edit.\n" % unicodedata.unidata_version,
           "\n",
           "pub(crate) const LATIN_START: u32 = 0x00C0;\n",
           "pub(crate) const EXT_ADD_START: u32 = 0x1E00;\n\n",
           table("LATIN", 0x00C0, 0x024F), "\n",
           table("LATIN_EXT_ADDITIONAL", 0x1E00, 0x1EFF)]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
