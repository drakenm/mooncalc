#!/usr/bin/env python3
"""Build the bright-star table shared by the egui and Tauri Sky tabs.

Reads the Yale Bright Star Catalogue, 5th revised edition (Hoffleit &
Warren 1991, BSC5), and writes `crates/mooncalc-app/src/sky/stars_data.rs`:
every star brighter than the magnitude limit with J2000 RA/Dec, V magnitude,
B-V colour index and a Bayer/Flamsteed label.

Usage, from the repository root (Python 3.10+, standard library only):

    python -I tools/stars/build_stars.py --download
    python -I tools/stars/build_stars.py --input path/to/bsc5.dat[.gz]

See tools/stars/README.md for the source and the selection rules.
"""

from __future__ import annotations

import argparse
import gzip
import pathlib
import sys
import urllib.request

URL = "http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz"
ROOT = pathlib.Path(__file__).resolve().parents[2]
DOWNLOAD = ROOT / "tools" / "stars" / "download"
OUTPUT = ROOT / "crates" / "mooncalc-app" / "src" / "sky" / "stars_data.rs"
MAG_LIMIT = 3.5
# BSC5 lists the recurrent nova T CrB (HR 5958) at its 1866 outburst peak,
# V = 2.0; it is normally near V = 10, so it is left out.
EXCLUDE = {5958}

GREEK = {
    "Alp": "α", "Bet": "β", "Gam": "γ", "Del": "δ", "Eps": "ε", "Zet": "ζ",
    "Eta": "η", "The": "θ", "Iot": "ι", "Kap": "κ", "Lam": "λ", "Mu": "μ",
    "Nu": "ν", "Xi": "ξ", "Omi": "ο", "Pi": "π", "Rho": "ρ", "Sig": "σ",
    "Tau": "τ", "Ups": "υ", "Phi": "φ", "Chi": "χ", "Psi": "ψ", "Ome": "ω",
}

# IAU-approved proper names (IAU WGSN) for the brightest stars, by HR number.
PROPER = {
    424: "Polaris", 1457: "Aldebaran", 1708: "Capella", 1713: "Rigel",
    1790: "Bellatrix", 1903: "Alnilam", 2061: "Betelgeuse", 2326: "Canopus",
    2491: "Sirius", 2618: "Adhara", 2943: "Procyon", 2990: "Pollux",
    2891: "Castor", 3982: "Regulus", 4730: "Acrux", 4763: "Gacrux",
    4853: "Mimosa", 5056: "Spica", 5267: "Hadar", 5340: "Arcturus",
    5459: "Rigil Kentaurus", 6134: "Antares", 6527: "Shaula", 6879: "Kaus Australis",
    7001: "Vega", 7121: "Nunki", 7557: "Altair", 7790: "Peacock", 7924: "Deneb",
    8425: "Alnair", 8728: "Fomalhaut", 15: "Alpheratz", 99: "Ankaa",
    168: "Schedar", 188: "Diphda", 337: "Mirach", 472: "Achernar",
    617: "Hamal", 911: "Menkar", 1017: "Mirfak", 1791: "Elnath",
    1948: "Alnitak", 2004: "Saiph", 2088: "Menkalinan", 2421: "Alhena",
    2693: "Wezen", 3165: "Naos", 3207: "Regor",
    3685: "Miaplacidus", 3634: "Suhail", 3748: "Alphard", 4057: "Algieba", 4301: "Dubhe",
    4534: "Denebola", 4905: "Alioth", 5054: "Mizar", 5191: "Alkaid",
    5288: "Menkent", 5793: "Alphecca", 5854: "Unukalhai", 6556: "Rasalhague",
    6705: "Eltanin", 6217: "Atria", 8162: "Alderamin", 8308: "Enif",
    8781: "Markab", 8775: "Scheat", 936: "Algol", 1165: "Alcyone",
    3307: "Avior", 7796: "Sadr", 6553: "Sargas", 4819: "Muhlifain",
}


def field(line: str, a: int, b: int) -> str:
    """Bytes a..b (1-based, inclusive) of a BSC5 record."""
    return line[a - 1 : b]


def label(line: str) -> str:
    """Bayer letter + constellation, else Flamsteed number + constellation."""
    flam = field(line, 5, 7).strip()
    bayer = field(line, 8, 10).strip()
    sup = field(line, 11, 11).strip()
    con = field(line, 12, 14).strip()
    if bayer and con:
        greek = GREEK.get(bayer, bayer)
        return f"{greek}{sup} {con}"
    if flam and con:
        return f"{flam} {con}"
    return ""


def parse(lines: list[str]) -> list[tuple]:
    stars = []
    for line in lines:
        line = line.rstrip("\n").ljust(197)
        vmag = field(line, 103, 107).strip()
        rah = field(line, 76, 77).strip()
        if not vmag or not rah:
            continue  # novae and other entries without positions
        v = float(vmag)
        if v >= MAG_LIMIT:
            continue
        hr = int(field(line, 1, 4))
        if hr in EXCLUDE:
            continue
        ra_h = int(rah) + int(field(line, 78, 79)) / 60 + float(field(line, 80, 83)) / 3600
        sign = -1.0 if field(line, 84, 84) == "-" else 1.0
        dec = sign * (
            int(field(line, 85, 86)) + int(field(line, 87, 88)) / 60 + int(field(line, 89, 90)) / 3600
        )
        bv_text = field(line, 110, 114).strip()
        bv = float(bv_text) if bv_text else 0.0
        stars.append((hr, ra_h * 15.0, dec, v, bv, label(line), PROPER.get(hr, "")))
    stars.sort(key=lambda s: s[3])
    return stars


def rust(stars: list[tuple]) -> str:
    out = [
        "// @generated by tools/stars/build_stars.py from the Yale Bright Star",
        "// Catalogue, 5th revised edition (Hoffleit & Warren 1991; public domain).",
        "// Do not edit by hand. See tools/stars/README.md.",
        "",
        "use super::stars::Star;",
        "",
        f"/// Every BSC5 star brighter than V = {MAG_LIMIT}, brightest first.",
        "// Magnitudes such as 3.14 are data, not approximations of π.",
        "#[allow(clippy::approx_constant)]",
        "#[rustfmt::skip]",
        "pub const BRIGHT_STARS: &[Star] = &[",
    ]
    for hr, ra, dec, v, bv, lab, name in stars:
        out.append(
            f"    Star {{ hr: {hr}, ra_deg: {ra:.5f}, dec_deg: {dec:.4f}, vmag: {v:.2f}, "
            f"bv: {bv:.2f}, label: {lab!r}, name: {name!r} }},".replace("'", '"')
        )
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--download", action="store_true", help=f"fetch {URL}")
    g.add_argument("--input", type=pathlib.Path, help="bsc5.dat or bsc5.dat.gz")
    args = ap.parse_args()
    path = args.input
    if args.download:
        DOWNLOAD.mkdir(parents=True, exist_ok=True)
        path = DOWNLOAD / "bsc5.dat.gz"
        urllib.request.urlretrieve(URL, path)
    raw = path.read_bytes()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    stars = parse(raw.decode("latin-1").splitlines())
    OUTPUT.write_text(rust(stars), encoding="utf-8", newline="\n")
    print(f"wrote {len(stars)} stars to {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
